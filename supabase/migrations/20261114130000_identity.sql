-- Identity: profiles, roles and preferences.
--
-- Every table has row-level security, and the policies use our own helpers
-- (app.current_user_id, app.is_guest) rather than vendor functions.
--
-- Three rules shape this migration:
--   1. A viewer reads and writes only their own rows. Proven by tests with
--      two distinct users against every table.
--   2. Guests are restricted: they may hold a profile and preferences, but
--      may not make themselves public.
--   3. Anything whose integrity matters - roles, the merge record - is
--      written only by a server function, never by a user-scoped client.

-- ---------------------------------------------------------------- types --

create type public.app_role as enum ('moderator', 'admin');
create type public.analytics_consent as enum ('unset', 'granted', 'denied');

-- ------------------------------------------------------------- profiles --

create table public.profiles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  handle text not null unique
    check (handle ~ '^[a-z0-9_]{3,24}$'),
  display_name text
    check (display_name is null or char_length(btrim(display_name)) between 1 and 60),
  avatar_path text
    check (avatar_path is null or char_length(avatar_path) <= 400),
  is_public boolean not null default false,
  locale text not null default 'en-GB'
    check (locale ~ '^[a-z]{2}(-[A-Z]{2})?$'),
  timezone text not null default 'Europe/London'
    check (char_length(timezone) between 3 and 64),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.profiles is
  'One row per account, created by the signup trigger. Private unless is_public.';

create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function app.set_updated_at();

-- ----------------------------------------------------------- user_roles --

create table public.user_roles (
  user_id uuid not null references auth.users (id) on delete cascade,
  role public.app_role not null,
  granted_by uuid references auth.users (id) on delete set null,
  granted_at timestamptz not null default now(),
  primary key (user_id, role)
);

comment on table public.user_roles is
  'Role grants. Written only by grant_role/revoke_role, never by a user-scoped client.';

-- ---------------------------------------------------------- preferences --

create table public.preferences (
  user_id uuid primary key references auth.users (id) on delete cascade,
  personalisation_enabled boolean not null default true,
  analytics_consent public.analytics_consent not null default 'unset',
  session_minutes integer not null default 10
    check (session_minutes between 5 and 60),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create trigger preferences_set_updated_at
before update on public.preferences
for each row execute function app.set_updated_at();

-- -------------------------------------------------------- account_merges --

create table public.account_merges (
  id bigint generated always as identity primary key,
  guest_user_id uuid not null,
  target_user_id uuid not null references auth.users (id) on delete cascade,
  moved jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  constraint account_merges_distinct check (guest_user_id <> target_user_id)
);

comment on table public.account_merges is
  'Record of a guest account whose owner turned out to already have an account. Append-only.';

-- Guards edits only. Deletion is not blocked here because account deletion
-- must cascade: a merge record references the target account, and the right
-- to erasure outranks keeping the record. No user-scoped client holds a
-- delete grant, so the only way a row goes is with the account itself.
create trigger account_merges_no_update
before update on public.account_merges
for each row execute function app.forbid_update_delete();

-- ------------------------------------------------------------ functions --

-- Role check for policies and server code. SECURITY DEFINER so that reading
-- user_roles inside a user_roles policy cannot recurse.
create or replace function public.has_role(p_role public.app_role)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.user_roles r
    where r.user_id = app.current_user_id()
      and r.role = p_role
  );
$$;

comment on function public.has_role(public.app_role) is
  'Whether the current viewer holds a role. Roles live in a table, never in editable user metadata.';

-- A handle is generated by us. Provider metadata is never trusted for a
-- unique column: a collision there would abort account creation.
create or replace function app.generate_handle(p_seed text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_base text;
  v_candidate text;
  v_suffix text;
begin
  v_base := lower(coalesce(p_seed, ''));
  v_base := regexp_replace(v_base, '[^a-z0-9_]', '', 'g');
  v_base := left(v_base, 16);

  if char_length(v_base) < 3 then
    v_base := 'learner';
  end if;

  for attempt in 1 .. 12 loop
    if attempt = 1 then
      v_candidate := v_base;
    else
      -- pg_catalog.gen_random_uuid is core, so this works under the pinned
      -- empty search path and does not depend on where an extension lives.
      v_suffix := substr(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 1, 6);
      v_candidate := left(v_base, 24 - char_length(v_suffix) - 1) || '_' || v_suffix;
    end if;

    if not exists (select 1 from public.profiles p where p.handle = v_candidate) then
      return v_candidate;
    end if;
  end loop;

  -- Fall back to something that cannot realistically collide.
  return 'learner_' || substr(replace(pg_catalog.gen_random_uuid()::text, '-', ''), 1, 12);
end;
$$;

-- Creates the profile and preferences rows for a new account, including a
-- guest account. Runs as the definer because the new user has no session yet.
create or replace function app.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_seed text;
begin
  v_seed := coalesce(
    nullif(new.raw_user_meta_data ->> 'preferred_username', ''),
    nullif(split_part(coalesce(new.email, ''), '@', 1), ''),
    'learner'
  );

  insert into public.profiles (user_id, handle, display_name)
  values (
    new.id,
    app.generate_handle(v_seed),
    nullif(btrim(coalesce(new.raw_user_meta_data ->> 'full_name', '')), '')
  )
  on conflict (user_id) do nothing;

  insert into public.preferences (user_id)
  values (new.id)
  on conflict (user_id) do nothing;

  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute function app.handle_new_user();

-- Columns a viewer may never change on their own profile.
create or replace function app.protect_profile_columns()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  if new.user_id is distinct from old.user_id then
    raise exception 'profiles.user_id cannot be changed';
  end if;

  if new.created_at is distinct from old.created_at then
    raise exception 'profiles.created_at cannot be changed';
  end if;

  return new;
end;
$$;

create trigger profiles_protect_columns
before update on public.profiles
for each row execute function app.protect_profile_columns();

-- Records that a guest's owner turned out to already have an account.
--
-- It never writes to the target's profile or preferences: an existing
-- account's data is never silently overwritten by a merge. The guest's own
-- rows are left in place and removed later by the stale-guest job; when
-- learning data exists (Milestone 4) the move happens here, before that job
-- can run, and the counts are recorded in `moved`.
create or replace function public.merge_guest_into(p_guest_id uuid, p_target_id uuid)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_guest_is_anonymous boolean;
  v_target_is_anonymous boolean;
  v_merge_id bigint;
begin
  if p_guest_id = p_target_id then
    raise exception 'merge_guest_into: guest and target are the same account';
  end if;

  select is_anonymous into v_guest_is_anonymous from auth.users where id = p_guest_id;
  select is_anonymous into v_target_is_anonymous from auth.users where id = p_target_id;

  if v_guest_is_anonymous is null or v_target_is_anonymous is null then
    raise exception 'merge_guest_into: unknown account';
  end if;

  if not v_guest_is_anonymous then
    raise exception 'merge_guest_into: source account is not a guest';
  end if;

  if v_target_is_anonymous then
    raise exception 'merge_guest_into: target account is a guest';
  end if;

  -- Only the target may merge a guest into their own account.
  if app.current_user_id() is distinct from p_target_id then
    raise exception 'merge_guest_into: only the target account may do this';
  end if;

  insert into public.account_merges (guest_user_id, target_user_id, moved)
  values (p_guest_id, p_target_id, '{}'::jsonb)
  returning id into v_merge_id;

  return v_merge_id;
end;
$$;

-- Role changes. Admin only, and the last admin cannot be removed.
create or replace function public.grant_role(p_user_id uuid, p_role public.app_role)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.has_role('admin') then
    raise exception 'grant_role: administrator access required';
  end if;

  insert into public.user_roles (user_id, role, granted_by)
  values (p_user_id, p_role, app.current_user_id())
  on conflict (user_id, role) do nothing;
end;
$$;

create or replace function public.revoke_role(p_user_id uuid, p_role public.app_role)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.has_role('admin') then
    raise exception 'revoke_role: administrator access required';
  end if;

  if p_role = 'admin'
     and (select count(*) from public.user_roles where role = 'admin') <= 1 then
    raise exception 'revoke_role: the last administrator cannot be removed';
  end if;

  delete from public.user_roles where user_id = p_user_id and role = p_role;
end;
$$;

-- Guest accounts with no activity are removed. Scheduled; also callable by a
-- privileged client.
create or replace function app.purge_stale_guests(p_older_than interval default interval '30 days')
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_deleted integer;
begin
  delete from auth.users u
  where u.is_anonymous
    and u.created_at < now() - p_older_than;

  get diagnostics v_deleted = row_count;
  return v_deleted;
end;
$$;

-- ---------------------------------------------------------- row security --

alter table public.profiles enable row level security;
alter table public.user_roles enable row level security;
alter table public.preferences enable row level security;
alter table public.account_merges enable row level security;

-- profiles --------------------------------------------------------------

create policy profiles_select_own
on public.profiles for select
to authenticated
using (user_id = app.current_user_id());

create policy profiles_select_public
on public.profiles for select
to authenticated, anon
using (is_public);

create policy profiles_select_moderation
on public.profiles for select
to authenticated
using (public.has_role('moderator') or public.has_role('admin'));

-- A viewer updates only their own row, and a guest may not make a profile
-- public.
create policy profiles_update_own
on public.profiles for update
to authenticated
using (user_id = app.current_user_id())
with check (
  user_id = app.current_user_id()
  and (not app.is_guest() or is_public = false)
);

-- No insert or delete policy: rows are created by the signup trigger and
-- removed by account deletion cascading from auth.users.

-- user_roles ------------------------------------------------------------

create policy user_roles_select_own
on public.user_roles for select
to authenticated
using (user_id = app.current_user_id());

create policy user_roles_select_admin
on public.user_roles for select
to authenticated
using (public.has_role('admin'));

-- No write policy at all: grant_role and revoke_role are the only way in.

-- preferences -----------------------------------------------------------

create policy preferences_select_own
on public.preferences for select
to authenticated
using (user_id = app.current_user_id());

create policy preferences_update_own
on public.preferences for update
to authenticated
using (user_id = app.current_user_id())
with check (user_id = app.current_user_id());

-- account_merges --------------------------------------------------------

create policy account_merges_select_own
on public.account_merges for select
to authenticated
using (target_user_id = app.current_user_id());

-- ---------------------------------------------------------------- grants --

grant select, update on public.profiles to authenticated;
grant select on public.profiles to anon;
grant select on public.user_roles to authenticated;
grant select, update on public.preferences to authenticated;
grant select on public.account_merges to authenticated;

grant execute on function public.has_role(public.app_role) to authenticated, anon;
grant execute on function public.merge_guest_into(uuid, uuid) to authenticated;
grant execute on function public.grant_role(uuid, public.app_role) to authenticated;
grant execute on function public.revoke_role(uuid, public.app_role) to authenticated;

-- Maintenance functions stay with privileged callers only.
revoke all on function app.purge_stale_guests(interval) from public, anon, authenticated;

-- --------------------------------------------------------------- indexes --

create index profiles_public_idx on public.profiles (handle) where is_public;
create index user_roles_role_idx on public.user_roles (role);
create index account_merges_target_idx on public.account_merges (target_user_id, created_at desc);
