import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";
import { runPipeline, runTai } from "@/factory";
import {
  CLASSIFY_RULES,
  DEMO_DRAFTS,
  DEMO_NOW,
  DEMO_OBSERVATIONS_A,
  DEMO_OBSERVATIONS_B,
  fixtureAdapter,
} from "@/factory/fixtures";

/**
 * Local draft-generation demonstration + sample trend report + quality audit.
 *
 * Always asserts the deterministic outcome. When FACTORY_EMIT=1 it also writes
 * the inspectable artifacts under docs/samples/. Nothing is published or
 * written to any database.
 */
describe("factory demonstration (local, dry-run)", () => {
  const result = runPipeline(DEMO_DRAFTS, { now: DEMO_NOW });

  it("prepares eight evidence-backed drafts for the editorial queue, none published", () => {
    expect(result.dryRun).toBe(true);
    expect(result.summary.queued).toBe(8);
    expect(result.summary.requiringFactCheck).toBe(8);
    expect(result.summary.requiringSecondReviewer).toBe(2);
    for (const c of result.cards) {
      expect(c.reviewStatus).toBe("editorial_queue");
      // honesty: no claim is "verified" without a supplied quote
      expect(c.evidence.overall).toBe("cited_pending_verification");
    }
  });

  it("emits a TAI report that declares no live source is connected", async () => {
    const tai = await runTai(
      [
        fixtureAdapter("fixture-official", "official", DEMO_OBSERVATIONS_A),
        fixtureAdapter("fixture-institution", "institution", DEMO_OBSERVATIONS_B),
      ],
      CLASSIFY_RULES,
      { now: DEMO_NOW },
    );
    expect(tai.liveDataConnected).toBe(false);
    expect(tai.note).toMatch(/NOT VERIFIED/);

    if (process.env.FACTORY_EMIT === "1") {
      const dir = resolve(process.cwd(), "docs/samples");
      mkdirSync(dir, { recursive: true });
      writeFileSync(resolve(dir, "factory-draft-cards.json"), JSON.stringify(result, null, 2) + "\n");
      writeFileSync(resolve(dir, "tai-trend-report.json"), JSON.stringify(tai, null, 2) + "\n");
      writeFileSync(resolve(dir, "quality-audit.md"), renderAudit(result, tai));
    }
  });
});

function renderAudit(
  result: ReturnType<typeof runPipeline>,
  tai: Awaited<ReturnType<typeof runTai>>,
): string {
  const lines: string[] = [];
  lines.push("# VSHARES Content Factory — sample evidence & quality audit\n");
  lines.push(`- Generated by the local, dry-run pipeline at a fixed clock (${DEMO_NOW}).`);
  lines.push("- No card is published; no database is written. Every claim awaits human fact-check.\n");
  lines.push("## Draft cards prepared for the editorial queue\n");
  lines.push("| Slug | Category | Level | Source class | Composite | Review status | Needs fact-check | 2nd reviewer |");
  lines.push("|---|---|---|---|---|---|---|---|");
  for (const c of result.cards) {
    lines.push(
      `| ${c.slug} | ${c.category} | ${c.level} | ${c.evidence.sourceVerdict.sourceClass} | ${c.quality.composite} | ${c.reviewStatus} | ${c.requiresFactCheck ? "yes" : "no"} | ${c.safety.requiresSecondReviewer ? "yes" : "no"} |`,
    );
  }
  lines.push("\n## Evidence status (honest)\n");
  lines.push(
    "Every draft cites a reputable, identifiable source but carries NO supplied supporting quote, so each claim is `cited_pending_verification` — routed to a human, never auto-asserted as verified.\n",
  );
  lines.push("## TAI — sample trend intelligence\n");
  lines.push(`- ${tai.note}`);
  lines.push("\n| Trend | Category | Topic | Status | Momentum | Sources | Credibility | Expired |");
  lines.push("|---|---|---|---|---|---|---|---|");
  for (const p of tai.proposals) {
    lines.push(
      `| ${p.display} | ${p.category ?? "—"} | ${p.topic ?? "—"} | ${p.status} | ${p.momentum.momentum ?? "n/a"} | ${p.momentum.distinctSources} | ${p.credibility} | ${p.expired ? "yes" : "no"} |`,
    );
  }
  lines.push("");
  return lines.join("\n");
}
